package com.broll.gainea.client.game.map;

public final class Coordinates {
    private final float displayX;
    private final float displayY;
    public Coordinates(float displayX, float displayY) { this.displayX = displayX; this.displayY = displayY; }
    public float getDisplayX() { return displayX; }
    public float getDisplayY() { return displayY; }
}
